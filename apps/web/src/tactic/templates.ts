const T8 = [0, 1428, 2857, 4285, 5714, 7142, 8571, 10_000] as const;
const T8_TRANSITION = [0, 900, 1800, 2800, 3900, 5000, 6000, 7000] as const;

function player(id: string, team: "offense" | "defense", number: number, label = String(number)): PlayerActor {
  return { id, type: "player", team, number, label };
}

function ball(heldBy?: string): BallActor {
  return heldBy ? { id: "ball", type: "ball", heldBy } : { id: "ball", type: "ball" };
}

function kf(t: number, poses: PoseMap): Keyframe {
  return { t, poses };
}

export function localizedText(value: LocalizedText, lang: "zh" | "en") {
  return value[lang];
}

/** Clone a built-in before use so localized teaching copy never mutates the catalog. */
export function localizeTemplateDocument(
  template: Template,
  lang: "zh" | "en",
  t: (key: string) => string,
): TacticDocumentV1 {
  const document = structuredClone(template.document);
  document.meta = {
    ...document.meta,
    name: t(template.nameKey),
    description: t(template.descKey),
    templateId: template.id,
    templateVersion: template.version,
    templateSource: "builtin",
  };
  document.teams = {
    ...document.teams,
    offense: { ...document.teams.offense, label: lang === "zh" ? "进攻" : "Offense" },
    defense: { ...document.teams.defense, label: lang === "zh" ? "防守" : "Defense" },
  };

  if (lang === "zh" && document.events) {
    document.events = document.events.map((event, index) => {
      const copy = template.eventCopyZh?.[index];
      if (!copy) return event;
      const next = {
        ...event,
        ...(copy.note ? { note: copy.note } : {}),
        ...(copy.readTrigger ? { readTrigger: copy.readTrigger } : {}),
        ...(copy.playerTask ? { playerTask: copy.playerTask } : {}),
        ...(copy.commonMistake ? { commonMistake: copy.commonMistake } : {}),
        ...(copy.explanation
          ? { teaching: { ...(event.teaching ?? {}), explanation: copy.explanation } }
          : {}),
      } as (typeof document.events)[number];

      if (copy.optionLabels) {
        const options = (event as { options?: unknown }).options;
        if (Array.isArray(options)) {
          (next as { options?: unknown[] }).options = options.map((option, optionIndex) => {
            if (!option || typeof option !== "object") return option;
            const label = copy.optionLabels?.[optionIndex];
            return label ? { ...option, label } : option;
          });
        }
      }
      return next;
    });
  }
  return document;
}

