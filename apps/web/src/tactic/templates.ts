import type { TacticDocumentV1 } from "@basketball/shared";

/**
 * Built-ins are teaching-friendly snapshots of classic actions. Each template
 * includes realistic offensive spacing plus defensive coverage/rotation so the
 * motion trails show both sides of the read.
 */
export interface Template {
  id: string;
  version: number;
  nameKey: string;
  descKey: string;
  coaching: {
    phase: LocalizedText;
    level: "foundation" | "intermediate" | "advanced";
    format: string;
    coverage: LocalizedText;
    focus: LocalizedText[];
    reads: LocalizedText[];
    previewAtMs: number;
  };
  eventCopyZh?: Record<number, TemplateEventCopy>;
  document: TacticDocumentV1;
}

type LocalizedText = { zh: string; en: string };

type TemplateEventCopy = {
  note?: string;
  explanation?: string;
  readTrigger?: string;
  playerTask?: string;
  commonMistake?: string;
  optionLabels?: string[];
};

type PlayerActor = Extract<TacticDocumentV1["actors"][number], { type: "player" }>;
type BallActor = Extract<TacticDocumentV1["actors"][number], { type: "ball" }>;
type Keyframe = TacticDocumentV1["keyframes"][number];
type PoseMap = Keyframe["poses"];

